-- ============ GEOGRAPHY ============

CREATE TABLE districts (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  state      TEXT NOT NULL,
  boundary   GEOGRAPHY(MultiPolygon, 4326) NOT NULL,
  population INT CHECK (population >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT districts_state_name_key UNIQUE (state, name)
);
CREATE INDEX districts_boundary_gist ON districts USING GIST (boundary);

CREATE TABLE villages (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  district_id INT NOT NULL REFERENCES districts (id),
  name        TEXT NOT NULL,
  location    GEOGRAPHY(Point, 4326) NOT NULL,
  population  INT CHECK (population >= 0)
);
CREATE INDEX villages_location_gist ON villages USING GIST (location);
CREATE INDEX villages_district_id_idx ON villages (district_id);

-- ============ RESPONDERS & FACILITIES ============

CREATE TABLE rescue_teams (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  district_id         INT NOT NULL REFERENCES districts (id),
  name                TEXT NOT NULL,
  agency              rescue_agency NOT NULL,
  team_size           INT NOT NULL CHECK (team_size > 0),
  capabilities        TEXT[] NOT NULL DEFAULT '{}',
  base_location       GEOGRAPHY(Point, 4326) NOT NULL,
  -- Last position flushed from Redis. NOT NULL (initialised to base_location) so the
  -- nearest-team KNN orders by this one column and stays index-served; a COALESCE
  -- with base_location would force a sequential scan.
  current_location    GEOGRAPHY(Point, 4326) NOT NULL,
  location_updated_at TIMESTAMPTZ,
  is_available        BOOLEAN NOT NULL DEFAULT TRUE,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX rescue_teams_base_location_gist ON rescue_teams USING GIST (base_location);
CREATE INDEX rescue_teams_current_location_gist ON rescue_teams USING GIST (current_location);
CREATE INDEX rescue_teams_district_id_idx ON rescue_teams (district_id);

CREATE TABLE facilities (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  district_id    INT NOT NULL REFERENCES districts (id),
  kind           facility_kind NOT NULL,
  name           TEXT NOT NULL,
  location       GEOGRAPHY(Point, 4326) NOT NULL,
  address        TEXT,
  contact_phone  TEXT,
  capacity       INT NOT NULL CHECK (capacity >= 0),
  occupancy      INT NOT NULL DEFAULT 0,
  is_operational BOOLEAN NOT NULL DEFAULT TRUE,
  amenities      TEXT[] NOT NULL DEFAULT '{}',
  attributes     JSONB NOT NULL DEFAULT '{}',
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT facilities_occupancy_within_capacity CHECK (occupancy BETWEEN 0 AND capacity)
);
CREATE INDEX facilities_location_gist ON facilities USING GIST (location);
CREATE INDEX facilities_district_kind_idx ON facilities (district_id, kind);

CREATE TABLE facility_inventory (
  facility_id         UUID NOT NULL REFERENCES facilities (id) ON DELETE CASCADE,
  item                inventory_item NOT NULL,
  quantity            INT NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  low_stock_threshold INT CHECK (low_stock_threshold >= 0),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (facility_id, item)
);

