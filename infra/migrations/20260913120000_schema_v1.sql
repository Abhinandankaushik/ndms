  CONSTRAINT users_phone_e164 CHECK (phone ~ '^\+[1-9][0-9]{7,14}$'),
  CONSTRAINT users_rescue_team_requires_role CHECK (rescue_team_id IS NULL OR role = 'RESCUE_TEAM'),
  CONSTRAINT users_facility_requires_role CHECK (facility_id IS NULL OR role = 'FACILITY_MANAGER')
);
CREATE INDEX users_last_location_gist ON users USING GIST (last_location);
CREATE INDEX users_role_idx ON users (role);

-- ============ INCIDENTS (the canonical object) ============

CREATE TABLE incidents (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  client_uuid         UUID NOT NULL,
  district_id         INT NOT NULL REFERENCES districts (id),
  reporter_id         UUID NOT NULL REFERENCES users (id),
  type                disaster_type NOT NULL DEFAULT 'OTHER',
  status              incident_status NOT NULL DEFAULT 'REPORTED',
  is_sos              BOOLEAN NOT NULL DEFAULT FALSE,
  -- NULL when the device could not get a fix: a location-less SOS must still land.
  location            GEOGRAPHY(Point, 4326),
  location_source     location_source NOT NULL,
  location_accuracy_m REAL CHECK (location_accuracy_m >= 0),
  address_text        TEXT,
  description         TEXT,
  people_affected     INT NOT NULL DEFAULT 1 CHECK (people_affected >= 0),
  has_elderly         BOOLEAN NOT NULL DEFAULT FALSE,
  has_children        BOOLEAN NOT NULL DEFAULT FALSE,
  has_injured         BOOLEAN NOT NULL DEFAULT FALSE,
  priority_score      NUMERIC(5, 2) CHECK (priority_score BETWEEN 0 AND 100),
  severity_level      SMALLINT CHECK (severity_level BETWEEN 1 AND 5),
  duplicate_of        UUID REFERENCES incidents (id),
  -- Device clock; the queue orders by this because a report held offline for hours is
  -- older, not newer. Clamp in SQL on write with
  -- LEAST(GREATEST($reported_at, now() - interval '24 hours'), now()): the CHECK below
  -- rejects unclamped values, and clamping with the app server's clock can drift past now().
  reported_at         TIMESTAMPTZ NOT NULL,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at         TIMESTAMPTZ,
  CONSTRAINT incidents_client_uuid_key UNIQUE (client_uuid),
  CONSTRAINT incidents_reported_at_clamped CHECK (reported_at BETWEEN created_at - interval '24 hours' AND created_at),
  CONSTRAINT incidents_location_matches_source CHECK ((location IS NULL) = (location_source = 'NONE')),
  CONSTRAINT incidents_duplicate_requires_rejection CHECK (duplicate_of IS NULL OR (status = 'REJECTED_DUPLICATE' AND duplicate_of <> id))
);
CREATE INDEX incidents_location_gist ON incidents USING GIST (location);
CREATE INDEX incidents_district_status_reported_idx ON incidents (district_id, status, reported_at);
CREATE INDEX incidents_reporter_reported_idx ON incidents (reporter_id, reported_at DESC);

CREATE TABLE incident_status_log (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  incident_id UUID NOT NULL REFERENCES incidents (id),
  from_status incident_status,
  to_status   incident_status NOT NULL,
  changed_by  UUID REFERENCES users (id),
  note        TEXT,
  changed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- Automation may flag a report for review but never reject it; a rejection is
  -- always attributable to a person.
  CONSTRAINT incident_status_log_rejection_has_actor CHECK (to_status NOT IN ('REJECTED_DUPLICATE', 'REJECTED_FAKE') OR changed_by IS NOT NULL)
);
CREATE INDEX incident_status_log_incident_idx ON incident_status_log (incident_id, changed_at);

CREATE TABLE incident_reviews (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  incident_id         UUID NOT NULL REFERENCES incidents (id),
  reason              review_reason NOT NULL,
  related_incident_id UUID REFERENCES incidents (id),
  details             JSONB NOT NULL DEFAULT '{}',
  flagged_by          UUID REFERENCES users (id),
  status              review_status NOT NULL DEFAULT 'PENDING',
  resolved_by         UUID REFERENCES users (id),
  resolution_note     TEXT,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at         TIMESTAMPTZ,
  CONSTRAINT incident_reviews_resolution_has_actor CHECK (
    (status = 'PENDING' AND resolved_by IS NULL AND resolved_at IS NULL)
    OR (status = 'RESOLVED' AND resolved_by IS NOT NULL AND resolved_at IS NOT NULL)
  ),
  CONSTRAINT incident_reviews_related_is_other CHECK (related_incident_id <> incident_id)
);
CREATE INDEX incident_reviews_pending_idx ON incident_reviews (created_at) WHERE status = 'PENDING';
CREATE UNIQUE INDEX incident_reviews_one_pending_per_reason_idx ON incident_reviews (incident_id, reason) WHERE status = 'PENDING';

CREATE TABLE media (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  uploaded_by  UUID NOT NULL REFERENCES users (id),
  purpose      media_purpose NOT NULL,
  incident_id  UUID REFERENCES incidents (id),
  object_key   TEXT NOT NULL,
  content_type TEXT NOT NULL,
  size_bytes   BIGINT CHECK (size_bytes > 0),
  status       media_status NOT NULL DEFAULT 'PENDING',
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  confirmed_at TIMESTAMPTZ,
  CONSTRAINT media_object_key_key UNIQUE (object_key),
  CONSTRAINT media_incident_matches_purpose CHECK ((purpose = 'INCIDENT_ATTACHMENT') = (incident_id IS NOT NULL)),
  CONSTRAINT media_confirmed_at_matches_status CHECK ((status = 'CONFIRMED') = (confirmed_at IS NOT NULL))
);
CREATE INDEX media_incident_id_idx ON media (incident_id);
CREATE INDEX media_uploaded_by_idx ON media (uploaded_by);

-- ============ MISSIONS ============

CREATE TABLE missions (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  incident_id       UUID NOT NULL REFERENCES incidents (id),
  team_id           UUID NOT NULL REFERENCES rescue_teams (id),
  assigned_by       UUID NOT NULL REFERENCES users (id),
  status            mission_status NOT NULL DEFAULT 'ASSIGNED',
  eta_minutes       INT CHECK (eta_minutes >= 0),
  rejection_reason  TEXT,
  people_rescued    INT CHECK (people_rescued >= 0),
  injured_count     INT CHECK (injured_count >= 0),
  hospital_required BOOLEAN,
  outcome_notes     TEXT,
  assigned_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  accepted_at       TIMESTAMPTZ,
  reached_at        TIMESTAMPTZ,
  completed_at      TIMESTAMPTZ,
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT missions_rejection_has_reason CHECK (status <> 'REJECTED' OR rejection_reason IS NOT NULL)
);
CREATE INDEX missions_team_status_idx ON missions (team_id, status);
CREATE INDEX missions_incident_id_idx ON missions (incident_id);
-- Two officers clicking "Assign" at once must not dispatch the same team twice.
CREATE UNIQUE INDEX missions_one_open_per_incident_team_idx ON missions (incident_id, team_id)
  WHERE status IN ('ASSIGNED', 'ACCEPTED', 'EN_ROUTE', 'ON_SITE');

-- Durable trail only: live positions are served from Redis and flushed here in batches.
CREATE TABLE team_location_pings (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  team_id     UUID NOT NULL REFERENCES rescue_teams (id),
  mission_id  UUID REFERENCES missions (id),
  location    GEOGRAPHY(Point, 4326) NOT NULL,
  accuracy_m  REAL CHECK (accuracy_m >= 0),
  recorded_at TIMESTAMPTZ NOT NULL,
  flushed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX team_location_pings_team_recorded_idx ON team_location_pings (team_id, recorded_at);
CREATE INDEX team_location_pings_location_gist ON team_location_pings USING GIST (location);

-- ============ VOLUNTEERS ============

CREATE TABLE volunteer_profiles (
  user_id             UUID PRIMARY KEY REFERENCES users (id),
  skills              TEXT[] NOT NULL DEFAULT '{}',
  is_available        BOOLEAN NOT NULL DEFAULT TRUE,
  service_radius_km   SMALLINT NOT NULL DEFAULT 10 CHECK (service_radius_km BETWEEN 1 AND 100),
  verification_status verification_status NOT NULL DEFAULT 'PENDING',
  reviewed_by         UUID REFERENCES users (id),
  reviewed_at         TIMESTAMPTZ,
  rejection_reason    TEXT,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT volunteer_profiles_review_matches_status CHECK (
    (verification_status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL)
    OR (verification_status <> 'PENDING' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
  )
);
CREATE INDEX volunteer_profiles_skills_gin ON volunteer_profiles USING GIN (skills);

CREATE TABLE volunteer_tasks (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  district_id           INT NOT NULL REFERENCES districts (id),
  created_by            UUID NOT NULL REFERENCES users (id),
  incident_id           UUID REFERENCES incidents (id),
  facility_id           UUID REFERENCES facilities (id),
  title                 TEXT NOT NULL,
  description           TEXT,
  -- Empty means any verified volunteer may take it; otherwise matched with the && overlap operator.
  required_skills       TEXT[] NOT NULL DEFAULT '{}',
  location              GEOGRAPHY(Point, 4326) NOT NULL,
  status                volunteer_task_status NOT NULL DEFAULT 'OPEN',
  assigned_volunteer_id UUID REFERENCES users (id),
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  accepted_at           TIMESTAMPTZ,
  completed_at          TIMESTAMPTZ,
  CONSTRAINT volunteer_tasks_open_is_unassigned CHECK (status <> 'OPEN' OR assigned_volunteer_id IS NULL),
  CONSTRAINT volunteer_tasks_taken_is_assigned CHECK (status NOT IN ('ACCEPTED', 'COMPLETED') OR assigned_volunteer_id IS NOT NULL)
);
CREATE INDEX volunteer_tasks_location_gist ON volunteer_tasks USING GIST (location);
CREATE INDEX volunteer_tasks_open_district_idx ON volunteer_tasks (district_id) WHERE status = 'OPEN';
CREATE INDEX volunteer_tasks_volunteer_status_idx ON volunteer_tasks (assigned_volunteer_id, status);

-- ============ ALERTS & AUDIT ============

CREATE TABLE alerts (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  district_id  INT NOT NULL REFERENCES districts (id),
  created_by   UUID NOT NULL REFERENCES users (id),
  severity     alert_severity NOT NULL,
  title        TEXT NOT NULL,
  message      TEXT NOT NULL,
  -- Empty target_roles means every role; NULL geofence means the whole district.
  target_roles user_role[] NOT NULL DEFAULT '{}',
  geofence     GEOGRAPHY(MultiPolygon, 4326),
  issued_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at   TIMESTAMPTZ,
  cancelled_at TIMESTAMPTZ,
  CONSTRAINT alerts_expiry_after_issue CHECK (expires_at IS NULL OR expires_at > issued_at)
);
CREATE INDEX alerts_geofence_gist ON alerts USING GIST (geofence);
CREATE INDEX alerts_district_issued_idx ON alerts (district_id, issued_at DESC);

CREATE TABLE audit_log (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor_id    UUID REFERENCES users (id),
  action      TEXT NOT NULL,
  entity_type TEXT NOT NULL,
  entity_id   TEXT NOT NULL,
  metadata    JSONB NOT NULL DEFAULT '{}',
  ip_address  INET,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_entity_idx ON audit_log (entity_type, entity_id, occurred_at);
CREATE INDEX audit_log_actor_idx ON audit_log (actor_id, occurred_at);

