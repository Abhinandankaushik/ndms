CREATE TABLE users (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  phone             TEXT NOT NULL,
  full_name         TEXT,
  role              user_role NOT NULL DEFAULT 'CITIZEN',
  district_id       INT REFERENCES districts (id),
  rescue_team_id    UUID REFERENCES rescue_teams (id),
